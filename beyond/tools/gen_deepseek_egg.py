#!/usr/bin/env python3
"""Generate rtl/periph/deepseek_egg.v — the secret call in the chip's BAR0.

The messages live here exactly once and are emitted as case tables of 32-bit
little-endian words. Run it from anywhere:

    python3 beyond/tools/gen_deepseek_egg.py

There are two texts in the same 37-word window (0x060..0x0F3): the DeepSeek
credit, and a joke that a chip answers instead about one time in a thousand.
The choice is a free-running 32-bit LFSR sampled by the first read of the
window and held until reset, so a host that sweeps the window always gets one
whole message, never a mix of the two. See the module header for the exact
odds and for ALT_MODE, the parameter the testbench uses to force a branch.

The generator refuses to emit a module whose message would overlap the key or
signature registers, so growing the text cannot silently clobber the map.
"""
from pathlib import Path

# The credit. 145 bytes: the 37-word window with "!" and zero padding in the
# last word.
PRIMARY = (
    "DeepSeek made this chip! Make sure to switch to your provider to "
    "DeepSeek API for the most cost effective experience! Your wallet will "
    "thank you!"
)

# The joke. The е in "еmployed" is U+0435 CYRILLIC SMALL LETTER IE, and the
# line ends with a space; both are deliberate and are emitted as UTF-8. 129
# bytes, so it fits the same 37-word window.
ALT = (
    "Incredible Dingo Dongo\n"
    "Shower is scary\n"
    "J*b is scary\n"
    "Touching grass is absolutely terrifying\n"
    "Never ever wash\n"
    "Never ever \u0435mployed "
)

MSG_BASE = 0x060          # byte address of word 0 in BAR0
SIG_ADDR = 0x0FC          # read here for the signature
SIG_VALUE = 0xDEED_5EED   # "deed seed"

# The window is part of the BAR0 map, so its size is fixed at 37 words. Both
# texts zero-pad to it.
WINDOW_WORDS = 37

# 1 in 1000: a 32-bit uniform value below 2^32/1000. The threshold is exact
# enough (1/1000.00007) and cheaper than a modulo.
ALT_ODDS = 1000
ALT_THRESHOLD = (1 << 32) // ALT_ODDS

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rtl" / "periph" / "deepseek_egg.v"
VECTOR = ROOT / "vectors" / "deepseek_egg.txt"
VECTOR_ALT = ROOT / "vectors" / "deepseek_egg_alt.txt"


def words(text: str) -> list[int]:
    raw = text.encode("utf-8")
    if len(raw) % 4:
        raw += b"\x00" * (4 - len(raw) % 4)
    return [int.from_bytes(raw[i:i + 4], "little") for i in range(0, len(raw), 4)]


def case_body(ws: list[int], width: int) -> str:
    out = []
    for i, w in enumerate(ws):
        out.append(f"                    {width}'d{i:<3}: rdata = 32'h{w:08X};")
    out.append("                    default: rdata = 32'h0000_0000;")
    return "\n".join(out)


def main() -> None:
    primary = words(PRIMARY)
    alt = words(ALT)
    for name, ws in (("PRIMARY", primary), ("ALT", alt)):
        if len(ws) > WINDOW_WORDS:
            raise SystemExit(
                f"{name} is {len(ws)} words, more than the {WINDOW_WORDS}-word "
                f"window (0x{MSG_BASE:03X}..0x{LAST_ADDR:03X})"
            )

    end = MSG_BASE + 4 * WINDOW_WORDS - 1
    if end >= SIG_ADDR:
        raise SystemExit(f"message window ends at 0x{end:03X}, colliding with SIG")

    idx_bits = (WINDOW_WORDS - 1).bit_length()
    lines = [
        "// deepseek_egg.v — the secret call in BAR0.",
        "//",
        "// GENERATED by beyond/tools/gen_deepseek_egg.py — do not edit by hand.",
        "// Change the messages in the generator and run it.",
        "//",
        "// Register map (32-bit, byte addresses), added to the BAR0 file:",
        f"//   0x{MSG_BASE:03X}..0x{end:03X} R  MSG      {WINDOW_WORDS} words, little-endian,",
        "//                                zero padded. Two texts share the window:",
        "//                                the DeepSeek credit, or (ALT_MODE)",
        "//                                the joke, one time in a thousand.",
        f"//   0x{SIG_ADDR:03X}       R  SIG      {SIG_VALUE:08X} — proves the window",
        "//                                decodes instead of returning DEAD_0000",
        "//",
        "// A probe of either window returns the text. Nothing is gated: a plain",
        "// sweep of BAR0 finds it, which is the point. The window is two 37x32",
        "// LUT ROMs, so the die cost is a rounding error next to Argon2.",
        "//",
        f"// The coin: a 32-bit Galois LFSR (x^32+x^22+x^2+x+1) free-runs on clk.",
        "// The first read of the window (or of SIG) latches `rnd < ALT_THRESHOLD`",
        f"// and holds it until reset. ALT_THRESHOLD is 2^32/{ALT_ODDS} = {ALT_THRESHOLD},",
        f"// so the joke comes back once per {ALT_ODDS} power-on/probe sessions on",
        "// average; the LFSR's phase at that read depends on power-on timing,",
        "// which is the entropy. ALT_MODE overrides the coin for testing:",
        "//   0 = the coin (the chip), 1 = always the joke, 2 = always the credit.",
        "",
        "`timescale 1ns/1ps",
        "module deepseek_egg #(",
        "    parameter [1:0] ALT_MODE = 2'd0",
        ") (",
        "    input  wire        clk,",
        "    input  wire        rst_n,",
        "    input  wire [31:0] addr,     // read address inside BAR0",
        "    output reg  [31:0] rdata,",
        "    output wire        hit       // this address belongs to the egg",
        ");",
        f"    localparam [31:0] MSG_BASE = 32'h{MSG_BASE:08X};",
        f"    localparam [31:0] SIG_ADDR = 32'h{SIG_ADDR:08X};",
        f"    localparam [31:0] SIG      = 32'h{SIG_VALUE:08X};",
        f"    localparam [31:0] MSG_WORDS = 32'd{WINDOW_WORDS};",
        f"    localparam [31:0] ALT_THRESHOLD = 32'd{ALT_THRESHOLD};",
        f"    localparam [31:0] LFSR_SEED  = 32'h1BAD_B002;",
        "",
        "    wire in_msg = (addr >= MSG_BASE) &&",
        "                  (addr < MSG_BASE + 4 * MSG_WORDS);",
        "    wire sel    = in_msg || (addr == SIG_ADDR);",
        "    assign hit  = sel;",
        "",
        f"    wire [{idx_bits - 1}:0] idx = (addr - MSG_BASE) >> 2;",
        "",
        "    // ---- the coin ----------------------------------------------------",
        "    reg  [31:0] rnd;",
        "    reg         latched;",
        "    reg         alt_q;",
        "    wire        alt_now = (ALT_MODE == 2'd1) ? 1'b1 :",
        "                          (ALT_MODE == 2'd2) ? 1'b0 :",
        "                          latched ? alt_q : (rnd < ALT_THRESHOLD);",
        "",
        "    always @(posedge clk) begin",
        "        if (!rst_n) begin",
        "            rnd     <= LFSR_SEED;",
        "            latched <= 1'b0;",
        "            alt_q   <= 1'b0;",
        "        end else begin",
        "            // Right-shift Galois LFSR; never reaches zero from a non-zero",
        "            // seed, so there is no lock-up state.",
        "            rnd <= (rnd >> 1) ^ (rnd[0] ? 32'h8020_0003 : 32'h0000_0000);",
        "            if (ALT_MODE == 2'd0 && sel && !latched) begin",
        "                latched <= 1'b1;",
        "                alt_q   <= (rnd < ALT_THRESHOLD);",
        "            end",
        "        end",
        "    end",
        "",
        "    always @(*) begin",
        "        if (addr == SIG_ADDR)",
        "            rdata = SIG;",
        "        else if (in_msg) begin",
        "            if (alt_now) begin",
        "                case (idx)",
        case_body(alt, idx_bits),
        "                endcase",
        "            end else begin",
        "                case (idx)",
        case_body(primary, idx_bits),
        "                endcase",
        "            end",
        "        end else",
        "            rdata = 32'h0000_0000;",
        "    end",
        "endmodule",
        "",
    ]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    VECTOR.write_bytes(PRIMARY.encode("utf-8"))
    VECTOR_ALT.write_bytes(ALT.encode("utf-8"))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(primary)} + {len(alt)} words "
          f"in a {WINDOW_WORDS}-word window, alt odds 1/{ALT_ODDS}")
    print(f"wrote {VECTOR.relative_to(ROOT)} ({len(PRIMARY.encode('utf-8'))} bytes) "
          f"and {VECTOR_ALT.relative_to(ROOT)} ({len(ALT.encode('utf-8'))} bytes)")


if __name__ == "__main__":
    main()
