#!/usr/bin/env python3
"""Generate rtl/periph/deepseek_egg.v — the secret call in the chip's BAR0.

The message lives here exactly once and is emitted as a case table of 32-bit
little-endian words. Run it from anywhere:

    python3 beyond/tools/gen_deepseek_egg.py

The generator refuses to emit a module whose message would overlap the key or
signature registers, so growing the text cannot silently clobber the map.
"""
from pathlib import Path

MESSAGE = (
    "DeepSeek made this chip! Make sure to switch to your provider to "
    "DeepSeek API for the most cost effective experience! Your wallet will "
    "thank you!"
)

MSG_BASE = 0x060          # byte address of word 0 in BAR0
SIG_ADDR = 0x0FC          # read here for the signature
SIG_VALUE = 0xDEED_5EED   # "deed seed"
LAST_ADDR = 0x0FF         # inclusive end of the secret window

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "rtl" / "periph" / "deepseek_egg.v"
VECTOR = ROOT / "vectors" / "deepseek_egg.txt"


def words(text: str) -> list[int]:
    raw = text.encode("ascii")
    if len(raw) % 4:
        raw += b"\x00" * (4 - len(raw) % 4)
    return [int.from_bytes(raw[i:i + 4], "little") for i in range(0, len(raw), 4)]


def main() -> None:
    ws = words(MESSAGE)
    end = MSG_BASE + 4 * len(ws) - 1
    if end >= SIG_ADDR:
        raise SystemExit(
            f"message is {len(ws)} words, ending at 0x{end:03X}, which collides "
            f"with the signature register at 0x{SIG_ADDR:03X}"
        )

    lines = [
        "// deepseek_egg.v — the secret call in BAR0.",
        "//",
        "// GENERATED by beyond/tools/gen_deepseek_egg.py — do not edit by hand.",
        "// Change the message in the generator and run it.",
        "//",
        "// Register map (32-bit, byte addresses), added to the BAR0 file:",
        f"//   0x{MSG_BASE:03X}..0x{end:03X} R  MSG      {len(ws)} words, little-endian,",
        "//                                zero padded: the easter egg",
        f"//   0x{SIG_ADDR:03X}       R  SIG      {SIG_VALUE:08X} — proves the window",
        "//                                decodes instead of returning DEAD_0000",
        "//",
        "// A probe of either window returns the text. Nothing is gated: a plain",
        "// sweep of BAR0 finds it, which is the point. The window is 256 bytes of",
        "// LUT ROM, so the die cost is a rounding error next to the Argon2 array.",
        "",
        "`timescale 1ns/1ps",
        "module deepseek_egg (",
        "    input  wire [31:0] addr,     // read address inside BAR0",
        "    output reg  [31:0] rdata,",
        "    output wire        hit       // this address belongs to the egg",
        ");",
        f"    localparam [31:0] MSG_BASE = 32'h{MSG_BASE:08X};",
        f"    localparam [31:0] SIG_ADDR = 32'h{SIG_ADDR:08X};",
        f"    localparam [31:0] SIG      = 32'h{SIG_VALUE:08X};",
        f"    localparam [31:0] MSG_WORDS = 32'd{len(ws)};",
        "",
        "    wire in_msg = (addr >= MSG_BASE) &&",
        "                  (addr < MSG_BASE + 4 * MSG_WORDS);",
        "    wire sel    = in_msg || (addr == SIG_ADDR);",
        "    assign hit  = sel;",
        "",
        "    wire [5:0] idx = (addr - MSG_BASE) >> 2;",
        "",
        "    always @(*) begin",
        "        if (addr == SIG_ADDR)",
        "            rdata = SIG;",
        "        else if (in_msg) begin",
        "            case (idx)",
    ]
    for i, w in enumerate(ws):
        chunk = MESSAGE.encode("ascii")[4 * i:4 * i + 4].decode("ascii", "replace")
        chunk = chunk.replace("\\", "\\\\").replace('"', '\\"')
        chunk = "".join(c if 32 <= ord(c) < 127 else "." for c in chunk)
        lines.append(f"                6'd{i:<3}: rdata = 32'h{w:08X};  // \"{chunk}\"")
    lines += [
        f"                default: rdata = 32'h0000_0000;",
        "            endcase",
        "        end else",
        "            rdata = 32'h0000_0000;",
        "    end",
        "endmodule",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    # The testbench reads the same sentence, so the expected text is not
    # duplicated by hand in the test.
    VECTOR.parent.mkdir(parents=True, exist_ok=True)
    VECTOR.write_text(MESSAGE, encoding="ascii")
    print(f"wrote {OUT} ({len(ws)} words, 0x{MSG_BASE:03X}..0x{end:03X}, "
          f"{len(MESSAGE)} chars)")
    print(f"wrote {VECTOR}")


if __name__ == "__main__":
    main()
