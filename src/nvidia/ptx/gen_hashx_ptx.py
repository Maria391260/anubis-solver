#!/usr/bin/env python3
"""Generate hashx_interp.ptx -- the HashX proof-of-work interpreter in PTX.

The CUDA backend (../cuda/cuda_hashx.cu) carries one interpreter for the
whole GPU. This is the same interpreter written directly in PTX, so `ptxas`
can assemble it into a cubin with no nvcc in the loop.

One thread handles one nonce:

  1. expand the 8-word register file from the SipHash keys and the nonce,
     exactly as hashx.c / the CUDA kernel do;
  2. interpret the generated program (code_size instructions of four u32:
     opcode, dst, src, imm32), with r[] in local memory because the register
     index is data;
  3. finalise (SipHash permutation per 4-register lane, xor the halves),
     check `difficulty` leading zero bits and report the hit.

The digest is never trusted: the caller re-verifies it with the CPU.

    python3 gen_hashx_ptx.py > hashx_interp.ptx

Layout in local memory (96 bytes):

    0..63    r[0..7]   u64 register file      (indexable, hence local)
    64..95   hw[0..7]  u32 big-endian digest words

The opcode dispatch is a binary compare tree (4 branches) rather than an
11-way chain: the program is 512 instructions long, so the dispatch cost is
paid 512 times per nonce.
"""

import sys


def opcodes():
    """(name, has_dst, has_src) for the 11 HashX opcodes, in ISA order."""
    return [
        ("UMULH_R", True, True),
        ("SMULH_R", True, True),
        ("MUL_R", True, True),
        ("SUB_R", True, True),
        ("XOR_R", True, True),
        ("ADD_RS", True, True),
        ("ROR_C", True, True),
        ("ADD_C", True, True),
        ("XOR_C", True, True),
        ("TARGET", False, False),
        ("BRANCH", True, False),
    ]


class Emit:
    def __init__(self):
        self.lines = []

    def __call__(self, s=""):
        self.lines.append(s)

    def sipround(self):
        """SIPROUND on v0..v3 with %ta/%tb as scratch (rotl by constant)."""
        e = self

        def rotl(dst, n):
            e("    shl.b64 %%ta, %s, %d;" % (dst, n))
            e("    shr.u64 %%tb, %s, %d;" % (dst, 64 - n))
            e("    or.b64 %s, %%ta, %%tb;" % dst)

        e("    add.u64 %v0, %v0, %v1;")
        e("    add.u64 %v2, %v2, %v3;")
        rotl("%v1", 13)
        rotl("%v3", 16)
        e("    xor.b64 %v1, %v1, %v0;")
        e("    xor.b64 %v3, %v3, %v2;")
        rotl("%v0", 32)
        e("    add.u64 %v2, %v2, %v1;")
        e("    add.u64 %v0, %v0, %v3;")
        rotl("%v1", 17)
        rotl("%v3", 21)
        e("    xor.b64 %v1, %v1, %v2;")
        e("    xor.b64 %v3, %v3, %v0;")
        rotl("%v2", 32)

    def store_r(self, idx, reg):
        e = self
        e("    add.u64 %%ad, %%lmem, %d;" % (8 * idx))
        e("    st.local.u64 [%%ad], %s;" % reg)

    def load_r(self, idx, reg):
        e = self
        e("    add.u64 %%ad, %%lmem, %d;" % (8 * idx))
        e("    ld.local.u64 %s, [%%ad];" % reg)


def dispatch_tree(e, low, high, labels):
    """Emit a balanced compare tree over opcodes [low, high]."""
    if low == high:
        e("    bra %s;" % labels[low])
        return
    mid = (low + high) // 2
    e("    setp.le.u32 %%p, %%op, %d;" % mid)
    e("    @%%p bra BB_DISP_%d;" % (low * 1000 + mid))
    dispatch_tree(e, mid + 1, high, labels)
    e("BB_DISP_%d:" % (low * 1000 + mid))
    dispatch_tree(e, low, mid, labels)


def gen():
    e = Emit()
    names = [n for n, _, _ in opcodes()]
    labels = ["BB_C%d" % i for i in range(len(names))]

    e("/*")
    e(" * hashx_interp.ptx -- HashX proof-of-work interpreter (complete).")
    e(" *")
    e(" * Generated by gen_hashx_ptx.py; do not edit by hand.")
    e(" *")
    e(" * One thread hashes nonce = base + idx. The program is a list of")
    e(" * 16-byte instructions in global memory (opcode, dst, src, imm32),")
    e(" * exported by hashx_export(). The digest is re-verified by the CPU.")
    e(" *")
    e(" *   results: u32 count; u32 pad[3]; u32 nonces[8]; u32 hashes[8][8];")
    e(" */")
    e("")
    e(".version 7.5")
    e(".target sm_75")
    e(".address_size 64")
    e("")
    e(".visible .entry hashx_kernel(")
    e("    .param .u64 k0, .param .u64 k1, .param .u64 k2, .param .u64 k3,")
    e("    .param .u64 prog_ptr,")
    e("    .param .u32 code_size,")
    e("    .param .u32 difficulty,")
    e("    .param .u32 base,")
    e("    .param .u32 count,")
    e("    .param .u64 results_ptr")
    e(") {")
    e("    .reg .pred %p, %q;")
    e("    .reg .u32 %nt, %ct, %tx, %idx, %nonce, %i, %target, %be;")
    e("    .reg .u32 %result, %op, %dst, %src, %imm, %t32, %s32, %b;")
    e("    .reg .u32 %shift, %slot, %tmpw, %code_size, %difficulty;")
    e("    .reg .u32 %base, %count, %wlo, %b0, %b1, %b2, %b3;")
    e("    .reg .u64 %k0, %k1, %k2, %k3, %prog, %res;")
    e("    .reg .u64 %v0, %v1, %v2, %v3, %ta, %tb;")
    e("    .reg .u64 %d, %s, %x, %y, %ad, %ad2, %off, %lmem;")
    e("    .reg .u64 %w0, %w1, %w2, %w3;")
    e("")
    e("    .local .align 8 .b8 lmem[96];")
    e("")
    for p in ("k0", "k1", "k2", "k3"):
        e("    ld.param.u64 %%%s, [%s];" % (p, p))
    e("    ld.param.u64 %prog, [prog_ptr];")
    e("    ld.param.u32 %code_size, [code_size];")
    e("    ld.param.u32 %difficulty, [difficulty];")
    e("    ld.param.u32 %base, [base];")
    e("    ld.param.u32 %count, [count];")
    e("    ld.param.u64 %res, [results_ptr];")
    e("")
    e("    mov.u64 %lmem, lmem;")
    e("    mov.u32 %nt, %ntid.x;")
    e("    mov.u32 %ct, %ctaid.x;")
    e("    mov.u32 %tx, %tid.x;")
    e("    mad.lo.u32 %idx, %ct, %nt, %tx;")
    e("    setp.ge.u32 %p, %idx, %count;")
    e("    @%p bra BB_DONE;")
    e("    add.u32 %nonce, %base, %idx;")
    e("")
    e("    /* ---- expand the register file: SipHash(key, nonce) ---- */")
    e("    mov.u64 %v0, %k0;")
    e("    mov.u64 %v1, %k1;")
    e("    mov.u64 %v2, %k2;")
    e("    mov.u64 %v3, %k3;")
    e("    xor.b64 %v1, %v1, 0xee;")
    e("    cvt.u64.u32 %x, %nonce;")
    e("    xor.b64 %v3, %v3, %x;")
    e.sipround()
    e.sipround()
    e("    cvt.u64.u32 %x, %nonce;")
    e("    xor.b64 %v0, %v0, %x;")
    e("    xor.b64 %v2, %v2, 0xee;")
    for _ in range(4):
        e.sipround()
    for i in range(4):
        e.store_r(i, "%%v%d" % i)
    e("    xor.b64 %v1, %v1, 0xdd;")
    for _ in range(4):
        e.sipround()
    for i in range(4):
        e.store_r(4 + i, "%%v%d" % i)
    e("")
    e("    mov.u32 %i, 0;")
    e("    mov.u32 %target, 0;")
    e("    mov.u32 %be, 1;")
    e("    mov.u32 %result, 0;")
    e("")
    e("BB_LOOP:")
    e("    setp.ge.u32 %p, %i, %code_size;")
    e("    @%p bra BB_FINAL;")
    e("    mul.wide.u32 %off, %i, 16;")
    e("    add.u64 %ad, %prog, %off;")
    e("    ld.global.u32 %op, [%ad+0];")
    e("    ld.global.u32 %dst, [%ad+4];")
    e("    ld.global.u32 %src, [%ad+8];")
    e("    ld.global.u32 %imm, [%ad+12];")
    e("")
    dispatch_tree(e, 0, len(names) - 1, labels)
    e("    bra BB_NEXT;")
    e("")

    def addr_dst():
        e("    mul.wide.u32 %off, %dst, 8;")
        e("    add.u64 %ad2, %lmem, %off;")
        e("    ld.local.u64 %d, [%ad2];")

    def addr_src():
        e("    mul.wide.u32 %off, %src, 8;")
        e("    add.u64 %ad, %lmem, %off;")
        e("    ld.local.u64 %s, [%ad];")

    # case 0: UMULH_R
    e("BB_C0:                                 /* result = r[dst] = mulhi_u */")
    addr_dst()
    addr_src()
    e("    mul.hi.u64 %x, %d, %s;")
    e("    cvt.u32.u64 %result, %x;")
    e("    st.local.u64 [%ad2], %x;")
    e("    bra BB_NEXT;")
    # case 1: SMULH_R
    e("BB_C1:                                 /* r[dst] = mulhi_s */")
    addr_dst()
    addr_src()
    e("    mul.hi.s64 %x, %d, %s;")
    e("    cvt.u32.u64 %result, %x;")
    e("    st.local.u64 [%ad2], %x;")
    e("    bra BB_NEXT;")
    # case 2: MUL_R
    e("BB_C2:                                 /* r[dst] *= r[src] */")
    addr_dst()
    addr_src()
    e("    mul.lo.u64 %d, %d, %s;")
    e("    st.local.u64 [%ad2], %d;")
    e("    bra BB_NEXT;")
    # case 3: SUB_R
    e("BB_C3:                                 /* r[dst] -= r[src] */")
    addr_dst()
    addr_src()
    e("    sub.u64 %d, %d, %s;")
    e("    st.local.u64 [%ad2], %d;")
    e("    bra BB_NEXT;")
    # case 4: XOR_R
    e("BB_C4:                                 /* r[dst] ^= r[src] */")
    addr_dst()
    addr_src()
    e("    xor.b64 %d, %d, %s;")
    e("    st.local.u64 [%ad2], %d;")
    e("    bra BB_NEXT;")
    # case 5: ADD_RS
    e("BB_C5:                                 /* r[dst] += r[src] << (imm & 63) */")
    addr_dst()
    addr_src()
    e("    and.b32 %t32, %imm, 63;")
    e("    shl.b64 %x, %s, %t32;")
    e("    add.u64 %d, %d, %x;")
    e("    st.local.u64 [%ad2], %d;")
    e("    bra BB_NEXT;")
    # case 6: ROR_C
    e("BB_C6:                                 /* r[dst] = rotr(r[dst], imm & 63) */")
    addr_dst()
    e("    and.b32 %t32, %imm, 63;")
    e("    sub.u32 %s32, 0, %t32;")
    e("    and.b32 %s32, %s32, 63;")
    e("    shr.u64 %x, %d, %t32;")
    e("    shl.b64 %y, %d, %s32;")
    e("    or.b64 %d, %x, %y;")
    e("    st.local.u64 [%ad2], %d;")
    e("    bra BB_NEXT;")
    # case 7: ADD_C
    e("BB_C7:                                 /* r[dst] += sext(imm) */")
    addr_dst()
    e("    cvt.s64.s32 %x, %imm;")
    e("    add.u64 %d, %d, %x;")
    e("    st.local.u64 [%ad2], %d;")
    e("    bra BB_NEXT;")
    # case 8: XOR_C
    e("BB_C8:                                 /* r[dst] ^= sext(imm) */")
    addr_dst()
    e("    cvt.s64.s32 %x, %imm;")
    e("    xor.b64 %d, %d, %x;")
    e("    st.local.u64 [%ad2], %d;")
    e("    bra BB_NEXT;")
    # case 9: TARGET
    e("BB_C9:                                 /* branch target = i */")
    e("    mov.u32 %target, %i;")
    e("    bra BB_NEXT;")
    # case 10: BRANCH
    e("BB_C10:                                /* if (be && !(result & imm)) i = target */")
    e("    and.b32 %t32, %result, %imm;")
    e("    setp.eq.u32 %p, %t32, 0;")
    e("    setp.ne.u32 %q, %be, 0;")
    e("    and.pred %p, %p, %q;")
    e("    @%p mov.u32 %i, %target;")
    e("    @%p mov.u32 %be, 0;")
    e("    bra BB_NEXT;")
    e("")
    e("BB_NEXT:")
    e("    add.u32 %i, %i, 1;")
    e("    bra BB_LOOP;")
    e("")
    e("BB_FINAL:")
    e("    /* feed-forward: r0 += k0, r1 += k1, r6 += k2, r7 += k3 */")
    for i, k in ((0, "k0"), (1, "k1"), (6, "k2"), (7, "k3")):
        e.load_r(i, "%d")
        e("    add.u64 %%d, %%d, %%%s;" % k)
        e("    st.local.u64 [%ad], %d;")
    e("")
    for base in (0, 4):
        for i in range(4):
            e.load_r(base + i, "%%v%d" % i)
        e.sipround()
        for i in range(4):
            e.store_r(base + i, "%%v%d" % i)
    for i in range(4):
        e.load_r(i, "%x")
        e.load_r(4 + i, "%y")
        e("    xor.b64 %%%s, %%x, %%y;" % ("w%d" % i))
    e("")
    e("    /* digest words, big-endian, so the hit test is a shift on hw[] */")
    for i in range(4):
        for half in range(2):
            idx = 2 * i + half
            if half:
                e("    shr.u64 %%x, %%%s, 32;" % ("w%d" % i))
            else:
                e("    mov.u64 %%x, %%%s;" % ("w%d" % i))
            e("    cvt.u32.u64 %wlo, %x;")
            e("    and.b32 %b0, %wlo, 0x000000ff;")
            e("    shl.b32 %b0, %b0, 24;")
            e("    and.b32 %b1, %wlo, 0x0000ff00;")
            e("    shl.b32 %b1, %b1, 8;")
            e("    and.b32 %b2, %wlo, 0x00ff0000;")
            e("    shr.b32 %b2, %b2, 8;")
            e("    and.b32 %b3, %wlo, 0xff000000;")
            e("    shr.b32 %b3, %b3, 24;")
            e("    or.b32 %b0, %b0, %b1;")
            e("    or.b32 %b2, %b2, %b3;")
            e("    or.b32 %b0, %b0, %b2;")
            e("    add.u64 %%ad, %%lmem, %d;" % (64 + 4 * idx))
            e("    st.local.u32 [%ad], %b0;")
    e("")
    e("    /* difficulty: leading zero bits, MSB first */")
    e("    mov.u32 %b, 0;")
    e("BB_BIT:")
    e("    setp.ge.u32 %p, %b, %difficulty;")
    e("    @%p bra BB_HIT;")
    e("    shr.b32 %t32, %b, 5;")
    e("    mul.wide.u32 %off, %t32, 4;")
    e("    add.u64 %ad, %lmem, %off;")
    e("    ld.local.u32 %tmpw, [%ad+64];")
    e("    and.b32 %t32, %b, 31;")
    e("    sub.u32 %shift, 31, %t32;")
    e("    shr.u32 %tmpw, %tmpw, %shift;")
    e("    and.b32 %tmpw, %tmpw, 1;")
    e("    setp.ne.u32 %p, %tmpw, 0;")
    e("    @%p bra BB_DONE;")
    e("    add.u32 %b, %b, 1;")
    e("    bra BB_BIT;")
    e("")
    e("BB_HIT:")
    e("    atom.global.add.u32 %slot, [%res], 1;")
    e("    setp.lt.u32 %p, %slot, 8;")
    e("    @!%p bra BB_DONE;")
    e("    mul.wide.u32 %off, %slot, 4;")
    e("    add.u64 %ad, %res, %off;")
    e("    st.global.u32 [%ad+16], %nonce;")
    for i in range(8):
        e("    mul.wide.u32 %off, %slot, 32;")
        e("    add.u64 %ad, %res, %off;")
        e("    add.u64 %%ad, %%ad, %d;" % (48 + 4 * i))
        e("    ld.local.u32 %%tmpw, [%%lmem+%d];" % (64 + 4 * i))
        e("    st.global.u32 [%ad], %tmpw;")
    e("")
    e("BB_DONE:")
    e("    ret;")
    e("}")
    return "\n".join(e.lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(gen())
